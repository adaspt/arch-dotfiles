-- Noctalia's bar and panels animate themselves. Hyprland's layer animations on top of them cause
-- glitches, such as a panel tearing when reopened while it's closing.
hl.layer_rule({
    name  = "noctalia-no-anim",
    match = { namespace = "^noctalia-(bar-.+|notification|dock|panel|attached-panel|osd|window-switcher)$" },
    no_anim = true,
})

-- The Noctalia settings window floats
hl.window_rule({
    name  = "noctalia-settings",
    match = { class = "dev.noctalia.Noctalia" },
    float = true,
    size  = { 1080, 920 },
})

-- Chrome opens on workspace 3 (the right monitor), however it's started: Super+Shift+B, the
-- launcher or a link. Every new Chrome window goes there and is focused.
hl.window_rule({
    name      = "chrome-on-workspace-3",
    match     = { class = "^google-chrome$" },
    workspace = "3",
})

-- VS Code opens on workspace 2 (the middle monitor) the same way
hl.window_rule({
    name      = "vscode-on-workspace-2",
    match     = { class = "^(code|Code|com\\.microsoft\\.VSCode)$" },
    workspace = "2",
})

-- Hyprland-run windowrule
hl.window_rule({
    name  = "move-hyprland-run",
    match = { class = "hyprland-run" },

    move  = "20 monitor_h-120",
    float = true,
})

